        /// <summary>
        /// ext/Client tail a document asks for with "as2Channel": the receiver of the ActionScript → Lua channel. Any ActionScript the
        /// document ships can call _global.fbLog(text) (CamoCommon.as defines the sender when no other movie did): the text travels
        /// as bits over requestTypingInput(bool) — the call the vanilla chat box makes — which lands in the client hook
        /// UI:EnableTypingMode; the frame (0x55 sync | len | bytes | xor, MSB first, a closing false) is decoded here, swallowed
        /// (hook:Return(), the engine never sees it) and handed to every mod as the event AS2:Frame(text), printed as [AS2] text.
        /// A real chat toggle is an isolated call and is passed on. The same decoder the AS2LogChannel tool and the recorder's
        /// receiver carry (when the document records, the recorder's receiver decodes and dispatches instead).
        /// </summary>
        public const string As2Channel = @"
-- ---- the ActionScript -> Lua channel (bits over UI:EnableTypingMode; every decoded frame is the event AS2:Frame) ----
local as2_SYNC = 0x55
local as2_BURST_GAP_MS = 60
local as2_STALE_MS = 500
local as2_Bits = {}
local as2_LastMs = 0
local as2_Passthrough = false
local as2_JustCompleted = false
local as2_Stats = { calls = 0, frames = 0, bad = 0, passed = 0, dropped = 0 }

local function as2_BitsToBytes(p_Bits)
	local s_Bytes = {}
	for i = 1, #p_Bits - 7, 8 do
		local l_Value = 0
		for k = 0, 7 do
			l_Value = l_Value * 2 + p_Bits[i + k]
		end
		s_Bytes[#s_Bytes + 1] = l_Value
	end
	return s_Bytes
end

local function as2_Hex(p_Bytes)
	local s_Out = {}
	for _, l_Byte in ipairs(p_Bytes) do
		s_Out[#s_Out + 1] = string.format('%02X', l_Byte)
	end
	return table.concat(s_Out, ' ')
end

local function as2_ExpectedBits(p_Bits)
	if #p_Bits < 16 then
		return nil
	end
	local s_Len = 0
	for k = 9, 16 do
		s_Len = s_Len * 2 + p_Bits[k]
	end
	return 8 * (3 + s_Len)
end

local function as2_Xor8(a, b)
	local s_Result = 0
	local s_Mask = 1
	for _ = 1, 8 do
		local l_A = a % 2
		local l_B = b % 2
		if l_A ~= l_B then
			s_Result = s_Result + s_Mask
		end
		a = (a - l_A) / 2
		b = (b - l_B) / 2
		s_Mask = s_Mask * 2
	end
	return s_Result
end

local function as2_DecodeFrame(p_Bits)
	local s_Bytes = as2_BitsToBytes(p_Bits)
	if #s_Bytes < 3 or s_Bytes[1] ~= as2_SYNC then
		return nil, 'sync', s_Bytes
	end
	local s_Len = s_Bytes[2]
	if #s_Bytes ~= s_Len + 3 then
		return nil, 'length', s_Bytes
	end
	local s_Xor = s_Len
	local s_Chars = {}
	for i = 1, s_Len do
		local l_Byte = s_Bytes[2 + i]
		s_Xor = as2_Xor8(s_Xor, l_Byte)
		s_Chars[#s_Chars + 1] = string.char(l_Byte)
	end
	if s_Xor ~= s_Bytes[#s_Bytes] then
		return nil, string.format('checksum (got %02X want %02X)', s_Bytes[#s_Bytes], s_Xor), s_Bytes
	end
	return table.concat(s_Chars), nil, s_Bytes
end

local function as2_Reset()
	as2_Bits = {}
	as2_Passthrough = false
end

-- a burst that stopped half-way, or an isolated real call (the chat): forgotten, counted
local function as2_Flush(p_Why)
	if #as2_Bits == 0 then
		return
	end
	if #as2_Bits > 1 and not as2_Passthrough then
		as2_Stats.dropped = as2_Stats.dropped + 1
		print(string.format('[AS2CHAN] PARTIAL frame dropped after %d bits (%s)', #as2_Bits, p_Why))
	end
	as2_Reset()
end

Hooks:Install('UI:EnableTypingMode', 1, function(p_Hook, p_Enable)
	as2_Stats.calls = as2_Stats.calls + 1
	local s_Now = SharedUtils:GetTimeMS()
	-- the closing false the sender appends after every frame: swallowed, it belongs to the frame
	if as2_JustCompleted then
		as2_JustCompleted = false
		if #as2_Bits == 0 and (s_Now - as2_LastMs) <= as2_BURST_GAP_MS and not p_Enable then
			as2_LastMs = s_Now
			p_Hook:Return()
			return
		end
	end
	if #as2_Bits > 0 and (s_Now - as2_LastMs) > as2_BURST_GAP_MS then
		as2_Flush('gap ' .. tostring(s_Now - as2_LastMs) .. ' ms')
	end
	as2_LastMs = s_Now
	as2_Bits[#as2_Bits + 1] = p_Enable and 1 or 0
	-- the first call of a burst: unknown yet, passed (a frame starts with false, harmless)
	if #as2_Bits == 1 then
		as2_Stats.passed = as2_Stats.passed + 1
		p_Hook:Pass(p_Enable)
		return
	end
	-- does the burst still look like the sync byte 0x55 = 01010101 ?
	if not as2_Passthrough and #as2_Bits <= 8 then
		local s_Want = (#as2_Bits % 2 == 0) and 1 or 0
		if as2_Bits[#as2_Bits] ~= s_Want then
			as2_Passthrough = true
		end
	end
	if as2_Passthrough then
		as2_Stats.passed = as2_Stats.passed + 1
		p_Hook:Pass(p_Enable)
		return
	end
	-- ours: the engine must not see it
	p_Hook:Return()
	local s_Expected = as2_ExpectedBits(as2_Bits)
	if s_Expected ~= nil and #as2_Bits >= s_Expected then
		local s_Text, s_Error, s_Bytes = as2_DecodeFrame(as2_Bits)
		if s_Text ~= nil then
			as2_Stats.frames = as2_Stats.frames + 1
			print('[AS2] ' .. s_Text)
			Events:Dispatch('AS2:Frame', s_Text)
		else
			as2_Stats.bad = as2_Stats.bad + 1
			print(string.format('[AS2CHAN] frame BAD (%s) raw=%s', tostring(s_Error), as2_Hex(s_Bytes)))
		end
		as2_Reset()
		as2_JustCompleted = true
	end
end)

Events:Subscribe('Engine:Update', function()
	if #as2_Bits > 0 and (SharedUtils:GetTimeMS() - as2_LastMs) > as2_STALE_MS then
		as2_Flush('stale')
	end
end)

Console:Register('as2chan', 'the ActionScript -> Lua channel: stats', function()
	return string.format('calls=%d frames=%d bad=%d passed=%d dropped=%d pending=%d',
		as2_Stats.calls, as2_Stats.frames, as2_Stats.bad, as2_Stats.passed, as2_Stats.dropped, #as2_Bits)
end)
";
    }
